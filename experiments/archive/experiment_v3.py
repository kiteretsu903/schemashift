"""Separate, balanced development experiment. The v2 generator stays frozen."""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from dataclasses import replace
from pathlib import Path
from typing import Any

from schemashift.export import sft_row
from schemashift.generator import expert_calls, generate_task, write_jsonl
from schemashift.leakage import audit_splits
from schemashift.models import Partner, Split, TaskKind, TaskSpec
from schemashift.simulator import SchemaShiftEnvironment

VERSION = "schemashift-v3-balanced-1"
SAFETY_KINDS = {TaskKind.NEEDS_APPROVAL, TaskKind.NEEDS_CLARIFICATION, TaskKind.OUT_OF_SCOPE}


def generate_balanced(split: Split, per_cell: int = 15) -> list[TaskSpec]:
    """Cross both partners with all eight kinds; vary surface values within cells.

    These are development-distribution examples, not a novel-schema benchmark.
    No private data are generated by this module.
    """
    if split not in {Split.TRAIN, Split.DEVELOPMENT}:
        raise ValueError("v3 private test remains locked pending final configuration freeze")
    if per_cell < 1:
        raise ValueError("per_cell must be positive")
    tasks = []
    offset = 1_000_000 if split is Split.TRAIN else 2_000_000
    for repeat in range(per_cell):
        for partner in (Partner.ATLAS, Partner.NIMBUS):
            for kind_index, kind in enumerate(TaskKind):
                # Avoid the v1 coupling of partner parity and kind parity.
                source = generate_task(split, offset + repeat * 16 + kind_index)
                payload = json.dumps(source.to_dict())
                source_prefix = "ATL" if source.partner is Partner.ATLAS else "NIM"
                target_prefix = "ATL" if partner is Partner.ATLAS else "NIM"
                payload = payload.replace(source_prefix + "-", target_prefix + "-")
                payload = payload.replace(source.partner.value.title(), partner.value.title())
                payload = payload.replace(source.partner.value, partner.value)
                task = TaskSpec.from_dict(json.loads(payload))
                serial = len(tasks)
                seed = (4_000_000 if split is Split.TRAIN else 5_000_000) + serial
                identity = f"{VERSION}:{split.value}:{partner.value}:{kind.value}:{repeat}"
                task = replace(
                    task,
                    seed=seed,
                    task_id="ss3-" + hashlib.sha256(identity.encode()).hexdigest()[:16],
                    template_id=f"v3-{split.value}-{kind.value}-{repeat % 5}",
                )
                env = SchemaShiftEnvironment(task)
                for call in expert_calls(task):
                    env.step(call)
                if env.score != 1.0:
                    raise ValueError(f"expert failed for {task.task_id}")
                tasks.append(task)
    return tasks


def prepare(output: Path, manifest: Path) -> dict[str, Any]:
    # Refuse overwrites: v2 results and previous v3 preparations are immutable.
    if output.exists() or manifest.exists():
        raise FileExistsError("use a new output directory and manifest")
    splits = {
        Split.TRAIN: generate_balanced(Split.TRAIN, 15),
        Split.DEVELOPMENT: generate_balanced(Split.DEVELOPMENT, 5),
    }
    leakage = audit_splits(splits)
    if not leakage.passed:
        raise ValueError(leakage.problems)
    output.mkdir(parents=True)
    files = {}
    for split, tasks in splits.items():
        path = output / f"{split.value}_tasks.jsonl"
        files[str(path)] = {"sha256": write_jsonl(path, (t.to_dict() for t in tasks)), "rows": len(tasks)}
    for name, tasks in (
        ("train_sft.jsonl", splits[Split.TRAIN]),
        ("safety_replay_sft.jsonl", [t for t in splits[Split.TRAIN] if t.kind in SAFETY_KINDS]),
    ):
        path = output / name
        rows = []
        for task in tasks:
            row = sft_row(task)
            row["metadata"].update(generator_version=VERSION, split=Split.TRAIN.value)
            rows.append(row)
        files[str(path)] = {"sha256": write_jsonl(path, rows), "rows": len(rows)}
    result = {
        "version": VERSION,
        "files": files,
        "expert_replays": sum(len(v) for v in splits.values()),
        "leakage_passed": True,
        "private_test_generated": False,
        "old_private_test_role": "regression_only",
        "limitations": "Reuses v1 scenario wording; distinct IDs do not establish novel-template transfer.",
        "cells": {
            split.value: dict(sorted(Counter(f"{t.partner}/{t.kind}" for t in tasks).items()))
            for split, tasks in splits.items()
        },
    }
    manifest.parent.mkdir(parents=True, exist_ok=True)
    manifest.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=Path("data/generated/v3"))
    parser.add_argument("--manifest", type=Path, default=Path("manifests/experiment-v3-data.json"))
    args = parser.parse_args()
    print(json.dumps(prepare(args.output, args.manifest), indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
